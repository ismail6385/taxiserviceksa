// Writes lib/localized-pages.generated.ts: the English paths that have a real
// Arabic (/ar/...) or Urdu (/ur/...) version. The header language switcher and
// the "this page is available in Arabic/Urdu" banner use it to send a visitor
// to the same page in their language.
//
// A page only counts when its text is actually translated: mostly Arabic-script
// text and little English prose. Pages under /ar or /ur that are still in
// English are left out, so nobody is sent from English to more English.
//
// Runs before every build (see package.json "build:cf"); can also be run by hand:
//   node scripts/gen-localized-pages.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const APP = path.join(ROOT, 'app', '(main)');

function walk(dir, out = []) {
    for (const name of fs.readdirSync(dir)) {
        const p = path.join(dir, name);
        if (fs.statSync(p).isDirectory()) walk(p, out);
        else if (name === 'page.tsx') out.push(p);
    }
    return out;
}

function pageText(file) {
    let s = fs.readFileSync(file, 'utf8');
    const dir = path.dirname(file);
    for (const g of fs.readdirSync(dir)) if (/client\.tsx$/i.test(g)) s += fs.readFileSync(path.join(dir, g), 'utf8');
    return s.replace(/import[^\n]*\n/g, '').replace(/className="[^"]*"/g, '');
}

function translatedPaths(lang) {
    const base = path.join(APP, lang);
    if (!fs.existsSync(base)) return [];
    const out = [];
    for (const file of walk(base)) {
        const rel = path.relative(base, path.dirname(file)).split(path.sep).join('/');
        if (rel.includes('[')) continue; // dynamic templates share English data
        const s = pageText(file);
        const script = (s.match(/[؀-ۿ]/g) || []).length;
        const english = (s.match(/>\s*[A-Z][a-z]+(?:\s+[A-Za-z,.'-]+){2,}/g) || []).join('').length;
        if (script < 500 || script < english * 1.5) continue;
        const enPath = rel ? `/${rel}/` : '/';
        // Only pages that also exist in English can be switched to from English.
        const enFile = path.join(APP, ...(rel ? rel.split('/') : []), 'page.tsx');
        if (!fs.existsSync(enFile)) continue;
        out.push(enPath);
    }
    return out.sort();
}

const ar = translatedPaths('ar');
const ur = translatedPaths('ur');
const body = `// Generated by scripts/gen-localized-pages.mjs before each build. Do not edit by hand.
export const AR_PAGES: readonly string[] = ${JSON.stringify(ar, null, 4)};

export const UR_PAGES: readonly string[] = ${JSON.stringify(ur, null, 4)};
`;
fs.writeFileSync(path.join(ROOT, 'lib', 'localized-pages.generated.ts'), body.replace(/\n/g, '\r\n'));
console.log(`localized pages: ar ${ar.length}, ur ${ur.length}`);
